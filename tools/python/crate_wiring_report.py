#!/usr/bin/env python3
"""Generate a Markdown report of which workspace crates are WIRED vs UNWIRED.

A crate is WIRED if it is in the dependency closure of at least one workspace
BINARY target (the shipped products, e.g. ff-desktop, ff-mdx-app). Every other
workspace member is UNWIRED -- it exists in the tree but no product binary
reaches it yet. The classification is derived entirely from `cargo metadata`'s
real resolved dependency graph, so it cannot drift from the build the way a
hand-maintained list would.

Usage:
    python crate_wiring_report.py [--manifest <path>] \
        [--out <report.md>] [--log <log.txt>]

Defaults (relative to CWD, expected to be the repo root):
    --manifest  ./Cargo.toml
    --out       ./docs/project-management/crate-wiring-status.md
    --log       ./tools/logs/crate-wiring-report.txt

The report lists WIRED crates first, then UNWIRED crates, each sorted
alphabetically with a count. A short progress summary heads the file. The full
report is also written to the log so terminal capture is never the single
source of truth (see tooling.md). Read the log/report back to verify by effect.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import subprocess
import sys


def load_metadata(manifest: str) -> dict:
    """Run `cargo metadata` for the given manifest and parse the JSON."""
    result = subprocess.run(
        [
            "cargo",
            "metadata",
            "--format-version",
            "1",
            "--manifest-path",
            manifest,
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"cargo metadata failed (exit {result.returncode}):\n{result.stderr}"
        )
    return json.loads(result.stdout)


def workspace_member_ids(meta: dict) -> set[str]:
    """Package ids that are members of this workspace (not external deps)."""
    return set(meta.get("workspace_members", []))


def id_to_package(meta: dict) -> dict[str, dict]:
    return {p["id"]: p for p in meta["packages"]}


def binary_package_ids(meta: dict, members: set[str], by_id: dict[str, dict]) -> list[str]:
    """Workspace members that build at least one `bin` target."""
    bins = []
    for pid in members:
        pkg = by_id.get(pid)
        if not pkg:
            continue
        if any("bin" in t.get("kind", []) for t in pkg.get("targets", [])):
            bins.append(pid)
    return bins


def build_dep_graph(meta: dict) -> dict[str, list[str]]:
    """Map each package id to the ids it depends on, from the resolved graph."""
    graph: dict[str, list[str]] = {}
    resolve = meta.get("resolve") or {}
    for node in resolve.get("nodes", []):
        graph[node["id"]] = [dep for dep in node.get("dependencies", [])]
    return graph


def reachable_from(roots: list[str], graph: dict[str, list[str]]) -> set[str]:
    """All package ids reachable from the roots (roots included)."""
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        stack.extend(graph.get(cur, []))
    return seen


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default="Cargo.toml")
    parser.add_argument(
        "--out", default=os.path.join("docs", "project-management", "crate-wiring-status.md")
    )
    parser.add_argument(
        "--log", default=os.path.join("tools", "logs", "crate-wiring-report.txt")
    )
    args = parser.parse_args()

    meta = load_metadata(args.manifest)
    members = workspace_member_ids(meta)
    by_id = id_to_package(meta)
    graph = build_dep_graph(meta)

    bin_ids = binary_package_ids(meta, members, by_id)
    reached = reachable_from(bin_ids, graph)

    # Classify workspace members only (external deps are irrelevant here).
    wired_ids = members & reached
    unwired_ids = members - reached

    def names(ids: set[str]) -> list[str]:
        return sorted(by_id[i]["name"] for i in ids if i in by_id)

    wired = names(wired_ids)
    unwired = names(unwired_ids)
    bin_names = sorted(by_id[i]["name"] for i in bin_ids if i in by_id)
    total = len(members)

    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines: list[str] = []
    lines.append("# Crate Wiring Status")
    lines.append("")
    lines.append(
        "Generated by `tools/python/crate_wiring_report.py`. Do NOT hand-edit -- "
        "rerun the tool. A crate is WIRED when it is in the dependency closure "
        "of a workspace binary; UNWIRED crates exist in the tree but no product "
        "binary reaches them yet."
    )
    lines.append("")
    lines.append(f"- Generated: {now}")
    lines.append(f"- Product binaries (roots): {', '.join(bin_names) or '(none found)'}")
    lines.append(f"- Total workspace crates: {total}")
    lines.append(f"- Wired: {len(wired)}")
    lines.append(f"- Unwired: {len(unwired)}")
    if total:
        pct = 100.0 * len(wired) / total
        lines.append(f"- Progress: {pct:.1f}% wired")
    lines.append("")
    lines.append(f"## Wired crates ({len(wired)})")
    lines.append("")
    if wired:
        for name in wired:
            lines.append(f"- {name}")
    else:
        lines.append("_None._")
    lines.append("")
    lines.append(f"## Unwired crates ({len(unwired)})")
    lines.append("")
    if unwired:
        for name in unwired:
            lines.append(f"- {name}")
    else:
        lines.append("_None._")
    lines.append("")
    report = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(report)

    os.makedirs(os.path.dirname(os.path.abspath(args.log)), exist_ok=True)
    with open(args.log, "w", encoding="utf-8") as f:
        f.write(report)

    sys.stdout.write(report)
    sys.stdout.write(f"\nReport written to: {args.out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

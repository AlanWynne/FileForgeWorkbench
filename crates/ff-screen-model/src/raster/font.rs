#[cfg(test)]
mod tests {
    use super::*;

    // Validates: Req 23.2 -- every printable-ASCII code point has a glyph.
    #[test]
    fn printable_ascii_all_mapped() {
        for code in 0x20u32..=0x7E {
            let ch = char::from_u32(code).expect("ascii");
            let g = glyph(ch);
            // Space is legitimately all-zero; every other glyph has ink.
            if ch != ' ' {
                assert!(g.iter().any(|&col| col != 0), "glyph {ch:?} has no ink");
            }
        }
    }

    // Validates: Req 23.2 -- a non-ASCII code point maps to the fallback glyph.
    #[test]
    fn non_ascii_maps_to_fallback() {
        // U+2500 (box horizontal) is not in range; it must map to '?'.
        assert_eq!(glyph('\u{2500}'), glyph('?'));
    }
}

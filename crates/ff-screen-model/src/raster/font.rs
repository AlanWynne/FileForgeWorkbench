//! A compact, dependency-free 5x7 fixed-width ASCII bitmap font used to
//! rasterise the plain-text screen render to a PNG (screen-snapshot-scrm
//! Requirement 23.2). The glyphs cover printable ASCII (0x20..=0x7E); any other
//! code point renders as the fallback box (`?`-equivalent) glyph. The font is
//! column-major: each glyph is five columns, each column a 7-bit bitmap with
//! bit 0 the TOP row and bit 6 the BOTTOM row.
//!
//! This is intentionally a small, deterministic, monospace font: the point is a
//! faithful, reproducible raster of the SAME logical text render, not a
//! typographically rich image (Requirement 1, 23.2).

/// Glyph width in pixels (columns).
pub const GLYPH_W: usize = 5;
/// Glyph height in pixels (rows).
pub const GLYPH_H: usize = 7;

/// Return the five column bitmaps for `ch`, or the fallback glyph when `ch` is
/// outside the printable-ASCII range this font covers.
pub fn glyph(ch: char) -> [u8; GLYPH_W] {
    let code = ch as u32;
    if (0x20..=0x7E).contains(&code) {
        FONT_5X7[(code - 0x20) as usize]
    } else {
        // Fallback: the solid-ish question-mark glyph (code 0x3F).
        FONT_5X7[(0x3F - 0x20) as usize]
    }
}


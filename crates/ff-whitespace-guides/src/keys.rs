//! Configuration key constants for the `editor.*` namespace.
//!
//! All whitespace-and-guides settings are stored under these keys in
//! the configuration system.

/// Key for whitespace visibility mode.
pub const WHITESPACE_MODE: &str = "editor.whitespace_mode";

/// Key for tab draw mode.
pub const TAB_DRAW_MODE: &str = "editor.tab_draw_mode";

/// Key for whitespace glyph size.
pub const WHITESPACE_SIZE: &str = "editor.whitespace_size";

/// Key for indent guide mode.
pub const INDENT_GUIDES: &str = "editor.indent_guides";

/// Key for edge column mode.
pub const EDGE_MODE: &str = "editor.edge_mode";

/// Key for single edge column position.
pub const EDGE_COLUMN: &str = "editor.edge_column";

/// Key for single edge column colour.
pub const EDGE_COLOUR: &str = "editor.edge_colour";

/// Key for multi-edge column array.
pub const EDGE_COLUMNS: &str = "editor.edge_columns";

/// Key for wrap visual flags bitfield.
pub const WRAP_VISUAL_FLAGS: &str = "editor.wrap_visual_flags";

/// Key for wrap visual location.
pub const WRAP_VISUAL_LOCATION: &str = "editor.wrap_visual_location";

/// Key for wrap indent mode.
pub const WRAP_INDENT_MODE: &str = "editor.wrap_indent_mode";

/// Key for wrap start indent offset.
pub const WRAP_START_INDENT: &str = "editor.wrap_start_indent";
